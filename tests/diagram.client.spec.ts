// @vitest-environment jsdom
import { describe, expect, it } from 'vitest'
import { prepareDiagram } from '../src/client/svg.ts'

const bytes = (text: string) => new TextEncoder().encode(text)
const drawing = (body: string, dimensions = 'viewBox="-10 -20 1980 1120"') =>
  `<svg xmlns="http://www.w3.org/2000/svg" ${dimensions}>${body}</svg>`

describe('diagram import and rendering isolation', () => {
  it('preserves local arrows, gradients, CSS, labels and authored coordinates', () => {
    const result = prepareDiagram(bytes(drawing(`<defs>
      <marker id="arrow"><path d="M0 0L10 5L0 10Z"/></marker>
      <linearGradient id="paint"><stop offset="0" stop-color="red"/></linearGradient>
      <path id="symbol" d="M0 0L10 10"/></defs><style>.wire{stroke:#207f5d}</style>
      <path class="wire" marker-end="url(#arrow)" fill="url(#paint)" d="M10 20L200 100"/>
      <use href="#symbol"/><text x="10" y="20">DUT 原理图</text>`)))
    const doc = new DOMParser().parseFromString(result.html, 'text/html')
    expect(result).toMatchObject({ width: 1980, height: 1120 })
    expect(doc.querySelector('svg')?.getAttribute('viewBox')).toBe('-10 -20 1980 1120')
    expect(doc.querySelector('[marker-end]')?.getAttribute('marker-end')).toBe('url(#arrow)')
    expect(doc.querySelector('marker path')).not.toBeNull()
    expect(doc.querySelector('linearGradient')).not.toBeNull()
    expect(doc.querySelector('use')?.getAttribute('href')).toBe('#symbol')
    expect(doc.querySelector('text')?.textContent).toBe('DUT 原理图')
  })

  it('accepts XML preambles and fenced SVG generated by a model', () => {
    const svg = drawing('<text>Diagram</text>')
    expect(prepareDiagram(bytes(`<?xml version="1.0"?>\n<!-- generated -->${svg}`)).width).toBe(1980)
    expect(prepareDiagram(bytes(`\uFEFF\n\`\`\`svg\n${svg}\n\`\`\``)).height).toBe(1120)
  })

  it('resolves physical dimensions when viewBox is absent', () => {
    const result = prepareDiagram(bytes(drawing('', 'width="25.4mm" height="72pt"')))
    expect(result.width).toBeCloseTo(96)
    expect(result.height).toBeCloseTo(96)
    expect(result.html).toContain('viewBox="0 0 96 96"')
  })

  it.each([
    '<svg>broken', '<html/>', '<svg xmlns="http://www.w3.org/2000/svg"/>',
    drawing('', 'width="100%" height="100%"'), drawing('', 'viewBox="0 0 -1 100"'),
    '<!DOCTYPE svg [<!ENTITY x "expansion">]>' + drawing('<text>&x;</text>'),
  ])('rejects invalid or dimensionless input: %s', source => {
    expect(() => prepareDiagram(bytes(source))).toThrow()
  })

  it('rejects invalid UTF-8 instead of silently replacing bytes', () => {
    expect(() => prepareDiagram(new Uint8Array([0xff, 0xfe, 0x80]))).toThrow()
  })

  it('removes active content and external hrefs while providing a network-blocking policy', () => {
    const result = prepareDiagram(bytes(drawing(`<script>alert(1)</script>
      <foreignObject><div xmlns="http://www.w3.org/1999/xhtml">embedded</div></foreignObject>
      <animate attributeName="href" to="https://example.invalid"/>
      <image href="https://example.invalid/image.svg" onload="alert(1)"/>
      <use href="file:///private.svg#x"/><path onclick="alert(1)" d="M0 0L1 1"/>`)))
    const doc = new DOMParser().parseFromString(result.html, 'text/html')
    expect(doc.querySelector('script, foreignObject, animate, [onload], [onclick], [href]')).toBeNull()
    expect(doc.querySelector('meta[http-equiv="Content-Security-Policy"]')?.getAttribute('content'))
      .toContain("default-src 'none'; script-src 'none'")
  })
})
